#ifndef VENTUS_RT_BVH_H
#define VENTUS_RT_BVH_H

#include <stdint.h>

#define VENTUS_AS_MAGIC 0x53415456u /* "VTAS" little-endian */
#define VENTUS_AS_VERSION 1u

#define VENTUS_AS_HEADER_SIZE 80u
#define VENTUS_AS_BOX4_NODE_SIZE 128u
#define VENTUS_AS_TRIANGLE_NODE_SIZE 64u
#define VENTUS_AS_INSTANCE_NODE_SIZE 128u

#define VENTUS_AS_INVALID_NODE 0xffffffffu

enum ventus_as_type {
   VENTUS_AS_TYPE_BLAS = 1,
   VENTUS_AS_TYPE_TLAS = 2,
};

enum ventus_bvh_node_type {
   VENTUS_BVH_NODE_INVALID = 0,
   VENTUS_BVH_NODE_BOX4 = 1,
   VENTUS_BVH_NODE_TRIANGLE = 2,
   VENTUS_BVH_NODE_INSTANCE = 3,
   VENTUS_BVH_NODE_AABB = 4,
};

enum ventus_as_header_offset {
   VENTUS_AS_HEADER_MAGIC = 0x00,
   VENTUS_AS_HEADER_VERSION = 0x04,
   VENTUS_AS_HEADER_HEADER_SIZE = 0x06,
   VENTUS_AS_HEADER_TYPE = 0x08,
   VENTUS_AS_HEADER_FLAGS = 0x0c,
   VENTUS_AS_HEADER_ROOT_NODE_OFFSET = 0x10,
   VENTUS_AS_HEADER_ROOT_NODE_REF = 0x10,
   VENTUS_AS_HEADER_NODE_COUNT = 0x14,
   VENTUS_AS_HEADER_NODE_REGION_OFFSET = 0x18,
   VENTUS_AS_HEADER_NODE_REGION_SIZE = 0x1c,
   VENTUS_AS_HEADER_PRIMITIVE_REGION_OFFSET = 0x20,
   VENTUS_AS_HEADER_PRIMITIVE_COUNT = 0x24,
   VENTUS_AS_HEADER_INSTANCE_REGION_OFFSET = 0x28,
   VENTUS_AS_HEADER_INSTANCE_COUNT = 0x2c,
   VENTUS_AS_HEADER_ROOT_AABB_MIN_X = 0x30,
   VENTUS_AS_HEADER_ROOT_AABB_MIN_Y = 0x34,
   VENTUS_AS_HEADER_ROOT_AABB_MIN_Z = 0x38,
   VENTUS_AS_HEADER_ROOT_AABB_MAX_X = 0x3c,
   VENTUS_AS_HEADER_ROOT_AABB_MAX_Y = 0x40,
   VENTUS_AS_HEADER_ROOT_AABB_MAX_Z = 0x44,
};

enum ventus_box4_node_offset {
   VENTUS_BOX4_CHILD_REF = 0x00,
   VENTUS_BOX4_MIN_X = 0x10,
   VENTUS_BOX4_MIN_Y = 0x20,
   VENTUS_BOX4_MIN_Z = 0x30,
   VENTUS_BOX4_MAX_X = 0x40,
   VENTUS_BOX4_MAX_Y = 0x50,
   VENTUS_BOX4_MAX_Z = 0x60,
   VENTUS_BOX4_CHILD_FLAGS = 0x70,
};

enum ventus_triangle_node_offset {
   VENTUS_TRIANGLE_V0 = 0x00,
   VENTUS_TRIANGLE_V1 = 0x0c,
   VENTUS_TRIANGLE_V2 = 0x18,
   VENTUS_TRIANGLE_PRIMITIVE_ID = 0x24,
   VENTUS_TRIANGLE_GEOMETRY_ID = 0x28,
   VENTUS_TRIANGLE_SBT_RECORD_OFFSET = 0x2c,
   VENTUS_TRIANGLE_FLAGS = 0x30,
   VENTUS_TRIANGLE_INSTANCE_ID = 0x34,
   VENTUS_TRIANGLE_PRIMITIVE_ADDR_LO = 0x38,
   VENTUS_TRIANGLE_PRIMITIVE_ADDR_HI = 0x3c,
};

enum ventus_instance_node_offset {
   VENTUS_INSTANCE_BLAS_ADDR_LO = 0x00,
   VENTUS_INSTANCE_BLAS_ADDR_HI = 0x04,
   VENTUS_INSTANCE_CUSTOM_INDEX = 0x08,
   VENTUS_INSTANCE_MASK = 0x0c,
   VENTUS_INSTANCE_SBT_RECORD_OFFSET = 0x10,
   VENTUS_INSTANCE_FLAGS = 0x14,
   VENTUS_INSTANCE_INSTANCE_ID = 0x18,
   VENTUS_INSTANCE_RESERVED = 0x1c,
   VENTUS_INSTANCE_OBJECT_TO_WORLD = 0x20,
   VENTUS_INSTANCE_WORLD_TO_OBJECT = 0x50,
};

#define VENTUS_NODE_REF_TYPE_MASK 0x7u
#define VENTUS_NODE_REF_OFFSET_MASK (~VENTUS_NODE_REF_TYPE_MASK)

static inline uint32_t
ventus_bvh_make_node_ref(uint32_t offset, enum ventus_bvh_node_type type)
{
   return (offset & VENTUS_NODE_REF_OFFSET_MASK) | (uint32_t)type;
}

static inline uint32_t
ventus_bvh_node_ref_offset(uint32_t node_ref)
{
   return node_ref & VENTUS_NODE_REF_OFFSET_MASK;
}

static inline uint32_t
ventus_bvh_node_ref_type(uint32_t node_ref)
{
   return node_ref & VENTUS_NODE_REF_TYPE_MASK;
}

#endif
